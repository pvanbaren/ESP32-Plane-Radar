bool qualiaPanelInit() {
  Wire.begin(kI2cSda, kI2cScl);
  Wire.setClock(400000);

  // Probe the expander.
  Wire.beginTransmission(kExpanderAddr);
  if (Wire.endTransmission() != 0) {
    Serial.printf("TCA9554 not found at 0x%02X\n", kExpanderAddr);
    return false;
  }

  // Configure expander: set pin directions, disable polarity inversion.
  expanderWriteReg(kRegConfig, kConfigValue);
  expanderWriteReg(kRegPolarity, 0x00);

  // Idle CLK, deassert CS, assert RESET (active low), then release.
  pinChange(kBitCs, kBitClk | kBitReset);
  delay(10);
  pinChange(kBitReset, 0);
  delay(100);

  // Walk the init sequence.
  const size_t len = sizeof(kNv3052cInit);
  size_t i = 0;
  while (i < len) {
    const uint8_t cmd = kNv3052cInit[i];
    uint8_t data_size = kNv3052cInit[i + 1];
    const bool has_delay = (data_size & kDelayFlag) != 0;
    data_size &= ~kDelayFlag;
    const uint8_t* data = &kNv3052cInit[i + 2];

    spiSend(true, &cmd, 1);
    spiSend(false, data, data_size);

    pinChange(0, kBitClk);  // idle CLK
    pinChange(kBitCs, 0);   // deassert CS

    if (has_delay) {
      uint16_t delay_ms = kNv3052cInit[i + 2 + data_size];
      if (delay_ms == 255) {
        delay_ms = 500;
      }
      delay(delay_ms);
      ++data_size;  // account for the delay byte
    }
    i += 2 + data_size;
  }

  Serial.println("NV3052C panel init sent");
  return true;
}

