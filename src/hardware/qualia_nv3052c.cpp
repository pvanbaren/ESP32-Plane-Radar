uint8_t g_output_shadow = kInitialOutput;

void expanderWriteReg(uint8_t reg, uint8_t value) {
  Wire.beginTransmission(kExpanderAddr);
  Wire.write(reg);
  Wire.write(value);
  Wire.endTransmission();
}

// Update the output port: set `set_bits`, clear `clear_bits`, keep the rest.
void pinChange(uint8_t set_bits, uint8_t clear_bits) {
  g_output_shadow = (g_output_shadow & ~clear_bits) | set_bits;
  expanderWriteReg(kRegOutput, g_output_shadow);
}

// Bit-bang `len` bytes as 9-bit words (DC bit first, MSB->LSB), CPOL=CPHA=0.
// DC=0 for command bytes, DC=1 for data bytes.
void spiSend(bool is_command, const uint8_t* data, size_t len) {
  const int dc_mask = is_command ? 0x000 : 0x100;
  for (size_t i = 0; i < len; ++i) {
    int bits = data[i] | dc_mask;
    for (int j = 0; j < 9; ++j) {
      if (bits & 0x100) {
        pinChange(kBitMosi, kBitClk | kBitCs);
      } else {
        pinChange(0, kBitMosi | kBitClk | kBitCs);
      }
      pinChange(kBitClk, 0);  // latch on rising edge
      bits <<= 1;
    }
  }
}

